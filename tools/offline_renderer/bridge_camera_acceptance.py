"""Generated bridge camera pose / matrices / attached lights vs the probe render records.

For every bridge render of a v6.1 window: camera local and world TRS, worldToCamera,
cameraToWorld and culling matrices, and the world TRS of every light under the camera are
generated by ``hs2pipe.bridge_camera`` from the bridge request (target, ortho_size, yaw) and
compared bit for bit with the records.  ``--yaws`` additionally runs the generator for other
yaws (no reference: a yaw != 0 window is needed) and writes the predicted poses.

Inputs that are not exported and are taken as identity, labelled (probe v7 request):
the local TRS of ``CharaCamera`` (Main Camera's parent) and of ``Lights Custom`` (parent of
the Key/Back lights); the records are consistent with identity (camera local == world; light
world == camera * light local).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

F = np.float32
SESSION = Path('E:/HS2_offline_renderer_data/paired_session_v6_1_20261025')
IDENT = (np.zeros(3, F), np.array([0, 0, 0, 1], F), np.ones(3, F))


def rowmajor_to_colmajor(m):
    return np.asarray(m, F).reshape(4, 4).T.ravel()


def bits(a):
    return np.asarray(a, F).tobytes()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--nonce', action='append', required=True)
    ap.add_argument('--yaws', default='')
    ap.add_argument('--out', required=True, type=Path)
    a = ap.parse_args(argv)
    from src.render.unity_skin_emu import UnityPlayerEmu
    from src.render.hs2pipe import bridge_camera as bc, scene_v5 as sv
    emu = UnityPlayerEmu()
    geo = json.loads((SESSION / 'prepare_geometry_actor.json').read_text(encoding='utf-8'))
    gby = {t['name']: t for t in geo['transforms'] if t['name'] in ('CustomControl', 'CharaCustom')}

    def loc(t):
        return (np.asarray(t['local_position'], F), np.asarray(t['local_rotation_xyzw'], F),
                np.asarray(t['local_scale'], F))
    parent_chain = [IDENT, loc(gby['CustomControl']), loc(gby['CharaCustom'])]   # CharaCamera: identity (labelled)
    report = {'parent_chain_note': 'CharaCamera local TRS not exported: identity (labelled); CustomControl/CharaCustom '
                                   'from the session geometry export', 'windows': []}
    a.out.mkdir(parents=True, exist_ok=False)
    for n in a.nonce:
        W = SESSION / ('window_' + n)
        req = json.loads((SESSION / ('bridge_body_%s.json' % n)).read_text(encoding='utf-8'))
        recs = sv.resolve_records(json.loads((W / 'frames' / 'renders_005.json').read_text(encoding='utf-8')),
                                  sv.prior_seed(W, 5))
        pr = [r for r in recs if r['phase'] == 'pre_render' and r.get('bridge_render')]
        cs0 = pr[0]['data']['camera_state']
        pose = bc.capture_camera(emu, target=req['target'], ortho_size=req['ortho_size'], yaw=req['yaw'],
                                 field_of_view=cs0['field_of_view'], camera_local_scale=cs0['transform']['local_scale'],
                                 parent_chain=parent_chain)
        row = {'nonce': n, 'yaw': req['yaw'], 'look_rotation_path': pose['look_rotation_path'], 'renders': len(pr),
               'equal': {}, 'differ': []}

        def check(name, got, want):
            ok = bits(got) == bits(want)
            row['equal'][name] = row['equal'].get(name, 0) + int(ok)
            if not ok:
                row['differ'].append({'field': name, 'generated': [float(x) for x in np.ravel(got)],
                                      'record': [float(x) for x in np.ravel(want)]})
        for r in pr:
            cs = r['data']['camera_state']
            tr = cs['transform']
            check('camera_local_position', pose['local_position'], tr['local_position'])
            check('camera_local_rotation', pose['local_rotation'], tr['local_rotation'])
            check('camera_position', pose['world_position'], tr['position'])
            check('camera_rotation', pose['world_rotation'], tr['rotation'])
            proj = rowmajor_to_colmajor(cs['matrices']['projectionMatrix'])
            m = bc.camera_matrices(emu, pose, proj)
            check('worldToCameraMatrix', m['world_to_camera'], rowmajor_to_colmajor(cs['matrices']['worldToCameraMatrix']))
            check('cameraToWorldMatrix', m['camera_to_world'], rowmajor_to_colmajor(cs['matrices']['cameraToWorldMatrix']))
            check('cullingMatrix', m['culling'], rowmajor_to_colmajor(cs['matrices']['cullingMatrix']))
            for l in r['data']['lights']:
                lt = l['transform']
                if bits(lt['position']) != bits(pose['world_position']) and l['active_in_hierarchy']:
                    continue
                if not l['active_in_hierarchy']:
                    continue
                # under the camera: DHH_Light (direct child) or Lights Custom/<light> (identity parent, labelled)
                chain = [(np.asarray(lt['local_position'], F), np.asarray(lt['local_rotation'], F),
                          np.asarray(lt['local_scale'], F))]
                if l['id'] != -120688:
                    chain.append(IDENT)
                p, q = bc.attached_world(emu, chain, pose)
                check('light_%s_position' % l['id'], p, lt['position'])
                check('light_%s_rotation' % l['id'], q, lt['rotation'])
        row['differ'] = row['differ'][:12]
        report['windows'].append(row)
        print(json.dumps({k: row[k] for k in ('nonce', 'yaw', 'look_rotation_path', 'renders', 'equal')}),
              len(row['differ']))
    preds = []
    for y in [float(v) for v in a.yaws.split(',') if v.strip()]:
        req = json.loads((SESSION / ('bridge_body_%s.json' % a.nonce[0])).read_text(encoding='utf-8'))
        pose = bc.capture_camera(emu, target=req['target'], ortho_size=req['ortho_size'], yaw=y, field_of_view=23.0,
                                 camera_local_scale=[1, 1, 1], parent_chain=parent_chain)
        preds.append({'yaw': y, 'world_position': pose['world_position'].tolist(),
                      'world_rotation': pose['world_rotation'].tolist(), 'look_rotation_path': pose['look_rotation_path']})
    report['predicted_poses'] = preds
    (a.out / 'report.json').write_text(json.dumps(report, indent=1, default=str), encoding='utf-8')
    for p_ in preds:
        print(json.dumps(p_))


if __name__ == '__main__':
    main()
