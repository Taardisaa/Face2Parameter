"""Bridge capture camera at a given yaw, and the projection of world points to target pixels.

The camera pose is generated by the renderer's own source-derived module
``src.render.hs2pipe.bridge_camera`` (``MakerRenderStyleService.Capture``: position = target +
Quaternion.Euler(0, yaw, 0) * (0, 0, distance); LookAt(target); worldToCamera = Scale(1, 1, -1)
* GetWorldToLocalMatrixNoScale), exactly as ``frame_orchestrate_paired.bridge_camera_pose`` does,
from the window's request (target, ortho_size), the camera's field of view and its parent chain
(probe v7 ``transform_chains`` of the bridge render's pre_cull record).  The worldToCamera of the
window's own yaw is checked bit for bit against the render record (``check_record``).

The non-jittered projection (yaw-independent: perspective of the fixed field of view / aspect /
clip planes) is the record's ``nonJitteredProjectionMatrix``.  Pixels follow the chin fit's
convention (``protection.ViewCamera.pixels``): x = (ndc_x + 1) / 2 * W, y = (1 - ndc_y) / 2 * H,
top-down rows of the 1086 x 1448 target.  The projection is evaluated in float64 on the torch
tensors (GPU vertex-shader arithmetic is not part of the bit-exact claim).
"""
from __future__ import annotations

import json

import numpy as np
import torch

from .fp import DT

F = np.float32


class BridgeCamera:
    def __init__(self, w2c, proj, size=(1086, 1448), yaw=None, source=''):
        self.w2c = np.asarray(w2c, float).reshape(4, 4)
        self.proj = np.asarray(proj, float).reshape(4, 4)
        self.size = size
        self.yaw = yaw
        self.source = source

    def pixels(self, world):
        """world (n, 3) torch -> (n, 2) target pixels (differentiable)."""
        M = torch.as_tensor(self.proj @ self.w2c, dtype=DT)
        h = world @ M[:, :3].T + M[:, 3]
        ndc = h[:, :2] / h[:, 3:4]
        w, hgt = self.size
        return torch.stack([(ndc[:, 0] + 1) * 0.5 * w, (1 - ndc[:, 1]) * 0.5 * hgt], 1)


def _bridge_records(session, render=0):
    from src.render.hs2pipe import scene_v5 as sv
    cfg = session.cfg
    idx = session._window_index()
    recs = sv.resolve_records(json.loads((cfg.window / 'frames' / ('renders_%03d.json' % idx)).read_text(
        encoding='utf-8')), sv.prior_seed(cfg.window, idx))
    pr = [r for r in recs if r['phase'] == 'pre_render' and r.get('bridge_render')
          and r['bridge_render']['ordinal'] == render][0]
    pc = [r for r in recs if r['phase'] == 'pre_cull' and r.get('render_id') == pr['render_id']][0]
    return pr, pc


def record_camera(session, render=0):
    pr, _ = _bridge_records(session, render)
    m = pr['data']['camera_state']['matrices']
    req = json.loads((session.cfg.session / ('bridge_body_%s.json' % session.cfg.nonce)).read_text(encoding='utf-8'))
    return BridgeCamera(m['worldToCameraMatrix'], m['nonJitteredProjectionMatrix'], yaw=float(req.get('yaw', 0.0)),
                        source='render record (bridge render %d)' % render)


def generated_camera(session, yaw, render=0):
    """Bridge camera generated for ``yaw`` from the window's request, field of view and parent chain."""
    from src.render.unity_skin_emu import shared_emulator
    from src.render.hs2pipe import bridge_camera as bc
    emu = shared_emulator()
    pr, pc = _bridge_records(session, render)
    tc = pc['data'].get('transform_chains')
    if not tc or not tc.get('camera_main_chain'):
        raise ValueError('probe v7 transform_chains (camera parent chain) required')
    cm = tc['camera_main_chain']
    if cm[-1]['name'] != 'Main Camera':
        raise ValueError('camera_main_chain does not end at Main Camera')
    chain = [(np.asarray(e['local_position'], F), np.asarray(e['local_rotation'], F), np.asarray(e['local_scale'], F))
             for e in reversed(cm[:-1])]
    cs = pr['data']['camera_state']
    req = json.loads((session.cfg.session / ('bridge_body_%s.json' % session.cfg.nonce)).read_text(encoding='utf-8'))
    pose = bc.capture_camera(emu, target=req['target'], ortho_size=req['ortho_size'], yaw=yaw,
                             field_of_view=cs['field_of_view'], camera_local_scale=[1.0, 1.0, 1.0], parent_chain=chain)
    jit = np.asarray(cs['matrices']['projectionMatrix'], F).reshape(4, 4).T.ravel()
    mats = bc.camera_matrices(emu, pose, jit)
    w2c = np.asarray(mats['world_to_camera'], F).reshape(4, 4).T          # column-major -> row-major
    return BridgeCamera(w2c, cs['matrices']['nonJitteredProjectionMatrix'], yaw=float(yaw),
                        source='generated (hs2pipe.bridge_camera) for yaw %r' % float(yaw))


def check_record(session, render=0):
    """Generated camera at the window's own yaw == the render record's worldToCamera (bits)."""
    rec = record_camera(session, render)
    gen = generated_camera(session, rec.yaw, render)
    return np.asarray(gen.w2c, F).tobytes() == np.asarray(rec.w2c, F).tobytes()
